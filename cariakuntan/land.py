    for i,(t,s) in enumerate(nodes):
        x = xs[i]; d = f"M{cx},{cy+46} C{cx},{cy+130} {x},{ny-110} {x},{ny-34}"
        lnk += f'<path class="lnk" d="{d}"/>'; flo += f'<path class="flowl" d="{d}" style="animation-delay:{i*0.15:.2f}s"/>'
